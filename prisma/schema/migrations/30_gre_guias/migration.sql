-- Guías de remisión (Operaciones), 2026-11-13: una tabla nueva para registrar las GRE que entregan los clientes (y, más adelante, las que emitimos)
-- y vincularlas a un servicio. Aditiva e idempotente: no toca ninguna tabla existente.

CREATE TABLE IF NOT EXISTS `gre_guias` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `origen` VARCHAR(10) NOT NULL DEFAULT 'RECIBIDA',
  `tipo` VARCHAR(15) NOT NULL DEFAULT 'REMITENTE',
  `serie` VARCHAR(10) NOT NULL,
  `numero` VARCHAR(20) NOT NULL,
  `numero_completo` VARCHAR(32) NOT NULL,
  `emisor_ruc` VARCHAR(11) NOT NULL DEFAULT '',
  `fecha_emision` DATE NULL,
  `fecha_traslado` DATE NULL,
  `remitente_ruc` VARCHAR(15) NULL,
  `remitente_nombre` VARCHAR(200) NULL,
  `destinatario_doc` VARCHAR(15) NULL,
  `destinatario_nombre` VARCHAR(200) NULL,
  `transportista_ruc` VARCHAR(15) NULL,
  `transportista_nombre` VARCHAR(200) NULL,
  `modalidad` VARCHAR(10) NULL,
  `motivo` VARCHAR(80) NULL,
  `partida_ubigeo` VARCHAR(6) NULL,
  `partida_direccion` VARCHAR(255) NULL,
  `llegada_ubigeo` VARCHAR(6) NULL,
  `llegada_direccion` VARCHAR(255) NULL,
  `peso_kg` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  `bultos` INT NULL,
  `descripcion` VARCHAR(500) NULL,
  `items_json` LONGTEXT NULL,
  `placa` VARCHAR(20) NULL,
  `conductor_nombre` VARCHAR(150) NULL,
  `conductor_doc` VARCHAR(15) NULL,
  `licencia` VARCHAR(30) NULL,
  `trae_transporte` TINYINT(1) NOT NULL DEFAULT 0,
  `orden_servicio_id` INT NULL,
  `orden_servicio_codigo` VARCHAR(40) NULL,
  `estado` VARCHAR(15) NOT NULL DEFAULT 'REGISTRADA',
  `fuente` VARCHAR(10) NOT NULL DEFAULT 'MANUAL',
  `archivo_url` VARCHAR(500) NULL,
  `archivo_nombre` VARCHAR(200) NULL,
  `observaciones` TEXT NULL,
  `usuario` VARCHAR(150) NULL,
  `creado_en` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  `actualizado_en` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gre_guia` (`tipo`, `emisor_ruc`, `numero_completo`),
  KEY `idx_gre_os` (`orden_servicio_id`),
  KEY `idx_gre_os_codigo` (`orden_servicio_codigo`),
  KEY `idx_gre_estado` (`estado`),
  KEY `idx_gre_fecha` (`fecha_emision`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
