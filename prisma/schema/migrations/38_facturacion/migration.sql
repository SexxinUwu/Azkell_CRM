-- Facturación electrónica (2026-11-18): comprobantes emitidos por APISUNAT (factura 01, boleta 03, nota de crédito 07, nota de débito 08).
-- Aditiva e idempotente: solo crea tablas si faltan. No toca datos existentes.
-- Un comprobante puede cubrir varios servicios (una línea por servicio) o ser libre (sin servicio).

CREATE TABLE IF NOT EXISTS `facturacion_comprobantes` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `tipo_doc` VARCHAR(2) NOT NULL,
  `serie` VARCHAR(4) NOT NULL,
  `numero` VARCHAR(8) NOT NULL,
  `numero_completo` VARCHAR(14) NOT NULL,
  `fecha_emision` DATE NOT NULL,
  `hora_emision` VARCHAR(8) NULL,
  `fecha_vencimiento` DATE NULL,
  `cliente_id` INT NULL,
  `cliente_doc_tipo` VARCHAR(1) NOT NULL DEFAULT '6',
  `cliente_doc` VARCHAR(15) NOT NULL,
  `cliente_nombre` VARCHAR(255) NOT NULL,
  `cliente_direccion` VARCHAR(255) NULL,
  `moneda` VARCHAR(3) NOT NULL DEFAULT 'PEN',
  `tipo_cambio` DECIMAL(8,4) NULL,
  `forma_pago` VARCHAR(10) NOT NULL DEFAULT 'CONTADO',
  `dias_credito` INT NOT NULL DEFAULT 0,
  `base` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `igv` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `total` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `detraccion_pct` DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  `detraccion_monto` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `neto_pendiente` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `orden_compra` VARCHAR(60) NULL,
  `referencia` VARCHAR(120) NULL,
  `observacion` TEXT NULL,
  `doc_ref_id` INT NULL,
  `doc_ref_numero` VARCHAR(14) NULL,
  `motivo_codigo` VARCHAR(2) NULL,
  `motivo_texto` VARCHAR(250) NULL,
  `estado` VARCHAR(20) NOT NULL DEFAULT 'EMITIDO',
  `apisunat_document_id` VARCHAR(80) NULL,
  `apisunat_status` VARCHAR(30) NULL,
  `apisunat_faults` TEXT NULL,
  `pdf_url` TEXT NULL,
  `xml_url` TEXT NULL,
  `cdr_url` TEXT NULL,
  `datos_json` LONGTEXT NULL,
  `modo_emision` VARCHAR(10) NULL,
  `usuario` VARCHAR(150) NULL,
  `creado_en` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_comprobante_numero` (`tipo_doc`, `serie`, `numero`),
  KEY `idx_comp_cliente` (`cliente_doc`),
  KEY `idx_comp_fecha` (`fecha_emision`),
  KEY `idx_comp_ref` (`doc_ref_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `facturacion_items` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `comprobante_id` INT NOT NULL,
  `linea` INT NOT NULL DEFAULT 1,
  `orden_servicio` VARCHAR(40) NULL,
  `descripcion` VARCHAR(500) NOT NULL,
  `unidad` VARCHAR(5) NOT NULL DEFAULT 'ZZ',
  `cantidad` DECIMAL(12,3) NOT NULL DEFAULT 1.000,
  `valor_unitario` DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  `base` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `igv` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  PRIMARY KEY (`id`),
  KEY `idx_fitem_comp` (`comprobante_id`),
  KEY `idx_fitem_servicio` (`orden_servicio`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
